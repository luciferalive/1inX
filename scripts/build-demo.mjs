// Builds everything that is generated from the real source of truth
//   src/lib/rarity/questions.ts  and  src/lib/rarity/archetypes.ts
// into:
//   docs/index.html        the interactive browser demo (GitHub Pages)
//   cli/src/engine.mjs     the data + scoring engine used by the `1inx` terminal tool
//
// Run:  node scripts/build-demo.mjs
// No dependencies needed (Node 18+).

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => fs.readFileSync(path.join(root, p), "utf8");
const write = (p, s) => {
  fs.mkdirSync(path.dirname(path.join(root, p)), { recursive: true });
  fs.writeFileSync(path.join(root, p), s);
};

function between(src, startMarker, endMarker, name) {
  const s = src.indexOf(startMarker);
  if (s === -1) throw new Error(`Could not find "${startMarker}" in ${name}`);
  const e = endMarker ? src.indexOf(endMarker, s) : src.length;
  if (e === -1) throw new Error(`Could not find "${endMarker}" in ${name}`);
  return src.slice(s + startMarker.length, e).trim();
}

const questions = between(
  read("src/lib/rarity/questions.ts"),
  "export const QUESTIONS: Question[] =",
  "export const CATEGORIES",
  "questions.ts",
);
const archetypes = between(
  read("src/lib/rarity/archetypes.ts"),
  "export const ARCHETYPES: Record<string, Archetype> =",
  null,
  "archetypes.ts",
);

const template = read("scripts/demo-template.html");

// ---- 1) Browser demo ----
const html = template
  .replace("/*__QUESTIONS__*/", () => `const QUESTIONS = ${questions}`)
  .replace("/*__ARCHETYPES__*/", () => `const ARCHETYPES = ${archetypes}`);
write("docs/index.html", html);
write("docs/.nojekyll", "");
console.log(`Wrote docs/index.html (${(html.length / 1024).toFixed(1)} KB)`);

// ---- 2) Terminal tool engine (same scoring block as the demo) ----
const engine = between(template, "// ==ENGINE_START==", "// ==ENGINE_END==", "demo-template.html");
const cliEngine = `// AUTO-GENERATED by scripts/build-demo.mjs from src/lib/rarity/*.ts — do not edit by hand.
// Run \`node scripts/build-demo.mjs\` after changing questions, archetypes or the scoring.

const QUESTIONS = ${questions}

const ARCHETYPES = ${archetypes}

${engine}

export { QUESTIONS, ARCHETYPES, calculateRarity, formatOneInX };
`;
write("cli/src/engine.mjs", cliEngine);
console.log(`Wrote cli/src/engine.mjs (${(cliEngine.length / 1024).toFixed(1)} KB)`);
